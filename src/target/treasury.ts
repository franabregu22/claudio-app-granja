/**
 * Phase 27 (F27-D) — treasury, suppliers, purchases and instruments over the target schema
 * (RPC_CONTRACTS_V1 §TREASURY / §INSTRUMENTS / §PURCHASES; every table here is ADMIN-only by RLS).
 *
 * Authority split:
 *   - Balances: `report_balance_period` only (ACCOUNT = Σ financial_posting, SUPPLIER = supplier_ledger).
 *     The latest closing balance per entity is shown as read; nothing is summed or derived here.
 *   - Transfers, supplier payments, purchases, freight and the whole cheque / eCheq lifecycle: RPCs only.
 *     The backend writes the operation, postings, ledger entries, instrument state and audit rows.
 *   - Monthly trend: `pnl_summary` columns as read (P27-D2); no margin, flow or balance formula.
 */
