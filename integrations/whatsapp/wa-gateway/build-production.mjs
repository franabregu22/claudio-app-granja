// ADR-025 — builds the PRODUCTION wa-gateway Edge Function (granja-santo-tomas-v1, ycmkpnunhxluqqtecbyu) from the STAGING source.
//   node build-production.mjs   → production/supabase/{config.toml, functions/wa-gateway/handler.ts, index.ts}
//                                 production/tests/handler.prod.test.ts, production/SHA256SUMS
// The production function is the staging function validated on AppGranja with ONLY its project identity changed:
//   expected project = ycmkpnunhxluqqtecbyu; AppGranja (aplbsutpzgemexayldct) and Farm ERP (shdrztqgwpyyxclgfpdg) refused.
// Every substitution must apply exactly once, and the generated file is compared line by line with the source: any other
// difference stops the build. The staging sources (supabase/, tests/) are read, never written.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PROD = 'ycmkpnunhxluqqtecbyu', STAGING = 'aplbsutpzgemexayldct', FARM = 'shdrztqgwpyyxclgfpdg';
const OUT = join(HERE, 'production');
const read = (p) => readFileSync(join(HERE, p), 'utf8');
const sha = (s) => createHash('sha256').update(s).digest('hex');

/** applies [from, to] pairs (each exactly once); returns the text and the set of changed line numbers */
function transform(name, src, pairs) {
  let out = src;
  for (const [from, to] of pairs) {
    const n = out.split(from).length - 1;
    if (n !== 1) throw new Error(`${name}: expected exactly one "${from.slice(0, 60)}", found ${n}`);
    out = out.replace(from, to);
  }
  const a = src.split('\n'), b = out.split('\n');
  if (a.length !== b.length) throw new Error(`${name}: line count changed`);
  const changed = a.map((l, i) => (l === b[i] ? null : i + 1)).filter(Boolean);
  if (changed.length !== pairs.length) throw new Error(`${name}: ${changed.length} lines differ, ${pairs.length} substitutions expected`);
  return { out, changed };
}

// ── Edge handler: identity only ─────────────────────────────────────────────────────────────────────────────────────────
const handler = transform('handler.ts', read('supabase/functions/wa-gateway/handler.ts'), [
  [' * ADR-025 §18 — wa-gateway (STAGING: AppGranja only). Pure request handler; index.ts wires the runtime.',
   ' * ADR-025 §18 — wa-gateway (PRODUCTION: granja-santo-tomas-v1 only; GENERATED by build-production.mjs from the staging handler).'],
  [`export const STAGING_REF = '${STAGING}';`, `export const STAGING_REF = '${PROD}';   // PRODUCTION build: the only accepted project (identifier kept from the source)`],
  [`const FORBIDDEN_REFS = ['${PROD}', '${FARM}'];`, `const FORBIDDEN_REFS = ['${STAGING}', '${FARM}'];   // AppGranja staging and Farm ERP are refused`],
  [`'not the AppGranja staging project'`, `'not the granja-santo-tomas-v1 production project'`],
]);
const index = transform('index.ts', read('supabase/functions/wa-gateway/index.ts'), [
  ['// ADR-025 §18 — wa-gateway entrypoint (STAGING: AppGranja only).', '// ADR-025 §18 — wa-gateway entrypoint (PRODUCTION: granja-santo-tomas-v1 only; generated).'],
]);
// the only references to a project ref in the generated handler: the expected one and the refused ones
const refsOk = (t) => [...t.matchAll(/[a-z]{20}(?=\.supabase\.co|')/g)].every((m) => [PROD, STAGING, FARM].includes(m[0]));
if (!refsOk(handler.out) || !handler.out.includes(`export const STAGING_REF = '${PROD}'`) || !handler.out.includes(`FORBIDDEN_REFS = ['${STAGING}', '${FARM}']`)) {
  throw new Error('handler.ts: production identity not as expected');
}

// ── tests: the SAME staging test suite, with the expected / refused project swapped ─────────────────────────────────────
const SWAP = '__SWAP__';
const testsSrc = read('tests/handler.test.ts');
const tests = testsSrc.replaceAll(STAGING, SWAP).replaceAll(PROD, STAGING).replaceAll(SWAP, PROD)
  .replace("new URL('../n8n/logic.js', import.meta.url)", "new URL('../../n8n/logic.js', import.meta.url)")   // production/tests → n8n/
  .replace('// ADR-025 — wa-gateway handler tests', '// ADR-025 — wa-gateway handler tests (PRODUCTION build; generated from tests/handler.test.ts with the project refs swapped)');
if (tests.includes(`const BASE = 'https://${PROD}.supabase.co'`) === false) throw new Error('tests: production base not set');

// ── CLI config: deploy only with --project-ref ycmkpnunhxluqqtecbyu ────────────────────────────────────────────────────
const config = `# ADR-025 PRODUCTION — minimal CLI config for deploying wa-gateway to granja-santo-tomas-v1 ONLY (always with --project-ref ${PROD}).
# Generated by build-production.mjs. Meta sends no JWT: the webhook is authenticated by the Meta HMAC (verified in the database).
project_id = "wa-gateway-production"

[functions.wa-gateway]
verify_jwt = false
`;

const files = {
  'supabase/config.toml': config,
  'supabase/functions/wa-gateway/handler.ts': handler.out,
  'supabase/functions/wa-gateway/index.ts': index.out,
  'tests/handler.prod.test.ts': tests,
};
for (const [p, t] of Object.entries(files)) { mkdirSync(dirname(join(OUT, p)), { recursive: true }); writeFileSync(join(OUT, p), t); }
const sums = Object.entries(files).map(([p, t]) => `${sha(t)} *${p}`).join('\n') + '\n';
writeFileSync(join(OUT, 'SHA256SUMS'), sums);
console.log(`production Edge build: ${OUT}`);
console.log(`  handler.ts: ${handler.changed.length} lines differ from staging (lines ${handler.changed.join(', ')}) — identity only`);
console.log(`  index.ts:   ${index.changed.length} line differs (header comment)`);
console.log(`  source sha256: handler ${sha(read('supabase/functions/wa-gateway/handler.ts')).slice(0, 12)} · index ${sha(read('supabase/functions/wa-gateway/index.ts')).slice(0, 12)}`);
process.stdout.write(sums.split('\n').filter(Boolean).map((l) => `  ${l.slice(0, 12)}  ${l.slice(66)}`).join('\n') + '\n');
