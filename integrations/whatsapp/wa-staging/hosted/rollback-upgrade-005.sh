#!/usr/bin/env bash
# ADR-025 — rollback of upgrade-005 on AppGranja with the file apply-upgrade-005.sh generated FROM THE DATABASE before applying it
# (exact previous definitions of wa.validate_payload / wa_correct / wa_confirm; 005 adds no object). One transaction.
# Owner shell (password + typed phrase). NOT RUN without GO. Usage: rollback-upgrade-005.sh hosted/rollback-005-<ts>.sql
set -u
export MSYS_NO_PATHCONV=1
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -W)"
REF=aplbsutpzgemexayldct
HOST=aws-0-us-east-2.pooler.supabase.com
CLIENT=supabase_db_Claudio_app_Granja
RB="${1:-}"
exec > >(tee -a "$HERE/rollback-upgrade-005-output.txt") 2>&1
echo "######## run $(date '+%Y-%m-%d %H:%M:%S') — AppGranja staging ROLLBACK of upgrade-005"
stop() { echo "STOP: $*"; unset PGPASSWORD; echo "== done (STOPPED)"; exit 2; }
case "$REF" in ycmkpnunhxluqqtecbyu|shdrztqgwpyyxclgfpdg) stop "forbidden project";; esac
[ -f "$RB" ] || stop "rollback file missing (the one generated by apply-upgrade-005.sh)"
grep -q 'ROLLBACK_GUARD' "$RB" && [ "$(grep -c '^CREATE OR REPLACE FUNCTION ' "$RB")" = 3 ] && grep -q 'CREATE OR REPLACE FUNCTION public.wa_correct' "$RB" && grep -q 'CREATE OR REPLACE FUNCTION public.wa_confirm' "$RB"   && grep -q '^COMMIT;$' "$RB" && ! grep -qE '^(ERROR|FATAL|psql: error)' "$RB" || stop "not a complete rollback-005 file"
LINE=$(supabase projects list -o json 2>/dev/null | node -e "let d='';process.stdin.on('data',c=>d+=c).on('end',()=>{try{const j=JSON.parse(d.slice(d.search(/[\[{]/)));const p=j.find(x=>(x.ref||x.id)==='$REF');console.log(p?[p.ref||p.id,p.name,p.region,p.status].join('|'):'')}catch{console.log('')}})")
[ "$LINE" = "$REF|AppGranja|us-east-2|ACTIVE_HEALTHY" ] || stop "$REF is not AppGranja / us-east-2 / ACTIVE_HEALTHY"
echo "Pegá la contraseña de la BASE de AppGranja (no se ve) y Enter:"
read -rs PGPASSWORD; echo; PGPASSWORD=$(printf '%s' "$PGPASSWORD" | tr -d '\r\n'); [ -n "$PGPASSWORD" ] || stop "empty password"
export PGPASSWORD PGHOST="$HOST" PGPORT=5432 PGUSER="postgres.$REF" PGDATABASE=postgres PGSSLMODE=require
psqlc() { docker exec -i -e PGHOST -e PGPORT -e PGUSER -e PGPASSWORD -e PGDATABASE -e PGSSLMODE "$CLIENT" psql -X -q -t -A "$@" 2>&1 | tr -d '\r' | sed 's/^psql:<stdin>:[0-9]*: //'; }
echo "open drafts whose payment method is pending (the restored code cannot handle them; cancel them first if any): $(psqlc -c "SELECT count(*) FROM wa.draft WHERE state IN ('DRAFT','WAITING_MP','FAILED') AND payload ? 'method_pending'")"
echo "Escribí exactamente: ROLLBACK-005 WA STAGING $REF"
read -r C; [ "$C" = "ROLLBACK-005 WA STAGING $REF" ] || stop "confirmation phrase mismatch — nothing changed"
OUT=$(psqlc -f - < "$RB" | grep -E "^rollback\||ERROR|ROLLBACK_KEPT|ROLLBACK_GUARD")
echo "$OUT"
echo "$OUT" | grep -qE "ERROR|ROLLBACK_GUARD" && stop "rollback failed (transaction rolled back; upgrade-005 still in place)"
echo "preflight after rollback (005 must be absent): $(psqlc -f - < "$HERE/preflight-005.sql" | grep '^pre|upgrade-005 absent')"
unset PGPASSWORD
echo "== done"
