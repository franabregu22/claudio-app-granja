INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('purchase-attachments', 'purchase-attachments', false, 10485760,
        ARRAY['application/pdf', 'image/jpeg', 'image/png', 'image/webp']);

CREATE POLICY purchase_attachments_admin_select ON storage.objects
  FOR SELECT TO authenticated
  USING (CASE WHEN bucket_id = 'purchase-attachments' THEN public.current_app_role() = 'ADMIN' ELSE false END);

CREATE POLICY purchase_attachments_admin_insert ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (CASE WHEN bucket_id = 'purchase-attachments'
                   THEN public.current_app_role() = 'ADMIN' AND (storage.foldername(name))[1] = auth.uid()::TEXT
                   ELSE false END);

CREATE POLICY purchase_attachments_admin_delete ON storage.objects
  FOR DELETE TO authenticated
  USING (CASE WHEN bucket_id = 'purchase-attachments' THEN public.current_app_role() = 'ADMIN' ELSE false END);
