-- Adds:
--   * the PRIVATE Storage bucket `purchase-attachments`: 10 MB per object, MIME allowlist
--     application/pdf, image/jpeg, image/png, image/webp;
--   * three storage.objects policies for `authenticated`, confined to that bucket:
--       SELECT / DELETE: current_app_role() = 'ADMIN';
--       INSERT:          current_app_role() = 'ADMIN' AND the first path segment is the uploader's auth.uid()
--                        (object key `<auth-user-id>/<uuid>.<ext>`, generated by the frontend).
--     No UPDATE policy: an uploaded object is never overwritten or moved.
--     No policy for anon; OPERATOR gets false; nothing applies to any other bucket.
--
-- The role comes from the single existing authority current_app_role() (RLS spec §2). It raises for a
-- caller without an active profile, so it is evaluated inside CASE only for rows of this bucket: CASE
-- evaluates the bucket test first, and every other bucket's rows get `false` without calling it.
--
-- No public table, column, function or grant changes: the SECURITY DEFINER set stays at 62,
-- purchase_attachment keeps its metadata columns, register_purchase is unchanged.
